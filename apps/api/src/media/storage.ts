import { Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { mkdir, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Env } from '../config/env.validation';

/**
 * Where uploaded files live. LocalDiskStorage is for development and single-server
 * setups (the VPS keeps uploads on a Docker volume). An S3 / Cloudflare R2
 * implementation can replace it without touching callers.
 */
export abstract class Storage {
  abstract put(key: string, body: Buffer, contentType: string): Promise<string>;
  abstract remove(key: string): Promise<void>;
  /** Public URL prefix every stored file starts with. */
  abstract get baseUrl(): string;
}

@Injectable()
export class LocalDiskStorage extends Storage {
  private readonly logger = new Logger(LocalDiskStorage.name);

  constructor(private readonly config: ConfigService<Env, true>) {
    super();
  }

  get root(): string {
    return path.resolve(this.config.get('UPLOAD_DIR', { infer: true }));
  }

  get baseUrl(): string {
    return this.config.get('MEDIA_BASE_URL', { infer: true }).replace(/\/$/, '');
  }

  async put(key: string, body: Buffer): Promise<string> {
    const file = this.safePath(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, body, { flag: 'wx' }); // never overwrite an existing file
    return `${this.baseUrl}/${key}`;
  }

  async remove(key: string): Promise<void> {
    try {
      await unlink(this.safePath(key));
    } catch (e) {
      this.logger.warn(`Could not delete ${key}: ${(e as Error).message}`);
    }
  }

  /** Keys are generated by us, but refuse anything that would escape the upload folder. */
  private safePath(key: string): string {
    const file = path.resolve(this.root, key);
    if (!file.startsWith(this.root + path.sep)) throw new Error(`Invalid storage key: ${key}`);
    return file;
  }
}
